// ---------- D3 mục 7.2 → config keys ----------

const TIERS = ['app', 'channel', 'video', 'scene', 'frame'];

function baseType(t) {
  if (/^string\[\]/.test(t)) return 'string[]';
  if (/^(number|Ms)\b/.test(t)) return 'number';
  if (/^boolean/.test(t)) return 'boolean';
  if (/^VoiceId/.test(t)) return 'VoiceId';
  if (/^string/.test(t)) return 'string';
  throw new Error(`unknown config type in D3 7.2: ${t}`);
}

export function extractConfigKeys(md) {
  const text = norm(md);
  const sec = text.slice(text.indexOf('### 7.2'), text.indexOf('### 7.3'));
  const keys = [];
  for (const row of sec.split('\n').filter((l) => l.startsWith('| `'))) {
    const cells = row
      .split('|')
      .slice(1, -1)
      .map((c) => c.trim());
    const names = [...cells[0].matchAll(/`([^`]+)`/g)].map((m) => m[1]);
    const type = baseType(cells[1]);
    const tiers = /mọi tầng/.test(cells[2]) ? [...TIERS] : cells[2].split(',').map((s) => s.trim());
    for (const t of tiers) if (!TIERS.includes(t)) throw new Error(`unknown tier "${t}" in ${row}`);
    for (const name of names) {
      const pattern = name.includes('<');
      keys.push({ key: name, pattern, type, tiers });
    }
  }
  return keys;
}

function configKeysTs(keys) {
  const members = keys.map((k) =>
    k.pattern ? '`' + k.key.replace(/<[^>]+>/g, '${string}') + '`' : `'${k.key}'`,
  );
  return `${GENERATED('docs/03-spec-domain-artifacts.md mục 7.2')}export type ConfigKey =\n  | ${members.join('\n  | ')};\n`;
}

// ---------- bảng mã lỗi D3–D11 → errors.json ----------

export function extractErrors(files) {
  const map = new Map();
  for (const { name, text } of files) {
    let inTable = false;
    let hasRetry = false;
    for (const line of norm(text).split('\n')) {
      if (/^\|\s*Mã\s*\|/.test(line)) {
        inTable = true;
        hasRetry = /retryable/.test(line);
        continue;
      }
      if (!line.startsWith('|')) {
        inTable = false;
        continue;
      }
      if (!inTable) continue;
      const cells = line
        .split('|')
        .slice(1, -1)
        .map((c) => c.trim());
      const code = /^`(E_[A-Z0-9_]+)`$/.exec(cells[0])?.[1];
      if (!code) continue;
      const when = cells[1];
      const retryable = (hasRetry && /^có/.test(cells[2] ?? '')) || /\(retryable\)/.test(when);
      const entry = map.get(code) ?? { code, retryable: false, sources: [] };
      entry.retryable ||= retryable;
      entry.sources.push({ doc: `docs/${name}`, when });
      map.set(code, entry);
    }
  }
  return map;
}

function errorsJson(map, local) {
  for (const e of local.errors) {
    if (map.has(e.code)) throw new Error(`${e.code} in errors.local.json already defined in docs`);
    map.set(e.code, {
      code: e.code,
      retryable: e.retryable ?? false,
      sources: [{ doc: e.source, when: e.when }],
    });
  }
  const errors = [...map.values()].sort((a, b) => a.code.localeCompare(b.code));
  return `${JSON.stringify({ $comment: 'GENERATED by scripts/gen-contracts.mjs — DO NOT EDIT', errors }, null, 2)}\n`;
}

// ---------- schema ----------

async function generateSchemas(typesDir) {
  const { createGenerator } = await import('ts-json-schema-generator');
  const gen = createGenerator({
    path: path.join(typesDir, 'index.ts'),
    tsconfig: path.join(root, 'tsconfig.contracts.json'),
    type: '*',
    expose: 'export',
    topRef: true,
    jsDoc: 'extended',
    additionalProperties: false,
    skipTypeCheck: false,
  });
  const out = {};
  for (const t of SCHEMA_ROOTS) {
    const schema = gen.createSchema(t);
    // Id<'xx'> sinh ra {type: string}; thêm định dạng ID của D3 mục 2.
    for (const [name, def] of Object.entries(schema.definitions ?? {})) {
      const p = /^Id<"([a-z]{2})">$/.exec(name)?.[1];
      if (!p) continue;
      if (!ID_PREFIXES.includes(p)) throw new Error(`unknown ID prefix ${p}`);
      def.pattern = `^${p}_[0-9a-z]{8}$`;
    }
    out[t] = `${JSON.stringify(schema, null, 2)}\n`;
  }
  return out;
}

// ---------- chạy ----------

function plannedFiles() {
  const d3 = readFileSync(path.join(docs, '03-spec-domain-artifacts.md'), 'utf8');
  const d4 = readFileSync(path.join(docs, '04-spec-capability-gateway.md'), 'utf8');
  const d6 = readFileSync(path.join(docs, '06-spec-workflow-skill.md'), 'utf8');
  const d5 = readFileSync(path.join(docs, '05-spec-agent-runtime-policy.md'), 'utf8');
  const d8 = readFileSync(path.join(docs, '08-spec-music.md'), 'utf8');
  const keys = extractConfigKeys(d3);
  const errorDocs = readdirSync(docs)
    .filter((f) => /^(0[3-9]|1[01])-.*\.md$/.test(f))
    .sort()
    .map((name) => ({ name, text: readFileSync(path.join(docs, name), 'utf8') }));
  const local = JSON.parse(readFileSync(path.join(outDocs, 'errors.local.json'), 'utf8'));
  const d3Ts = extractD3Types(d3);
  const keysTs = configKeysTs(keys);
  const d6Ts = extractD6(d6, [
    { from: '../domain/d3', ts: d3Ts },
    { from: '../domain/config-keys', ts: keysTs },
  ]);
  const d4Ts = extractD4(d4, [
    { from: '../domain/d3', ts: d3Ts },
    { from: '../workflow/d6', ts: d6Ts },
  ]);
  return {
    d3Ts,
    d6Ts,
    d8Ts: extractD8(d8, [{ from: '../domain/d3', ts: d3Ts }]),
    d5Ts: extractD5(d5, [
      { from: '../domain/d3', ts: d3Ts },
      { from: '../gateway/d4', ts: d4Ts },
    ]),
    d4Ts: extractD4(d4, [
      { from: '../domain/d3', ts: d3Ts },
      { from: '../workflow/d6', ts: d6Ts },
    ]),
    keysTs,
    keysJson: `${JSON.stringify({ $comment: 'GENERATED from docs/03 mục 7.2 — DO NOT EDIT', keys }, null, 2)}
`,
    errors: errorsJson(extractErrors(errorDocs), local),
  };
}

const INDEX_TS = `${GENERATED('docs/contracts/domain/*')}export * from './d3';\nexport * from './markdown';\nexport * from './config-keys';\n`;
const ROOT_INDEX_TS = `${GENERATED('docs/contracts/*')}export * from './domain/index';\nexport * from './gateway/d4';\nexport * from './workflow/d6';\nexport * from './music/d8';\n`;

async function build() {
  const f = plannedFiles();
  const files = new Map([
    [path.join(outDocs, 'domain', 'd3.ts'), f.d3Ts],
    [path.join(outDocs, 'gateway', 'd4.ts'), f.d4Ts],
    [path.join(outDocs, 'workflow', 'd6.ts'), f.d6Ts],
    [path.join(outDocs, 'agent', 'd5.ts'), f.d5Ts],
    [path.join(outDocs, 'music', 'd8.ts'), f.d8Ts],
    [path.join(outDocs, 'index.ts'), ROOT_INDEX_TS],
    [path.join(outDocs, 'domain', 'config-keys.ts'), f.keysTs],
    [path.join(outDocs, 'domain', 'index.ts'), INDEX_TS],
    [path.join(outDocs, 'domain', 'config-keys.json'), f.keysJson],
    [path.join(outDocs, 'errors.json'), f.errors],
  ]);
  // Schema sinh từ type đã ghi (cần file trên đĩa) → dùng thư mục tạm khi --check.
  const tmp = path.join(root, 'node_modules', '.cache', 'sf-contracts');
  mkdirSync(tmp, { recursive: true });
  for (const [file, content] of files) {
    if (!file.endsWith('.ts')) continue;
    const dest = path.join(tmp, path.relative(outDocs, file));
    mkdirSync(path.dirname(dest), { recursive: true });
    writeFileSync(dest, content);
  }
  writeFileSync(
    path.join(tmp, 'domain', 'markdown.ts'),
    readFileSync(path.join(outDocs, 'domain', 'markdown.ts'), 'utf8'),
  );
  const schemas = await generateSchemas(tmp);
  for (const [t, json] of Object.entries(schemas)) {
    files.set(path.join(outDocs, 'domain', 'schemas', `${t}.schema.json`), json);
  }
  // Bản dùng trong core (rootDir = src): type gộp + schema/errors/keys dạng module TS.
  const coreTypes =
    `${GENERATED('docs/contracts/domain/*.ts')}` +
    [
      f.d3Ts,
      readFileSync(path.join(outDocs, 'domain', 'markdown.ts'), 'utf8'),
      f.keysTs,
      f.d6Ts,
      f.d4Ts,
      f.d5Ts,
      f.d8Ts,
    ]
      .map((s) =>
        s
          .replace(/^\/\/ GENERATED.*\n/, '')
          .replace(/^import type [\s\S]*?from '\.\.?\/[a-z0-9/-]+';\n/gm, ''),
      )
      .join('\n');
  const schemaModule =
    `${GENERATED('docs/contracts/domain/schemas/*.schema.json')}export const schemas = {\n` +
    Object.entries(schemas)
      .map(([t, json]) => `  ${t}: ${json.trimEnd().replace(/\n/g, '\n  ')},`)
      .join('\n') +
    `\n} as const;\n\nexport type SchemaRoot = keyof typeof schemas;\n`;
  files.set(path.join(outCore, 'types.ts'), coreTypes);
  files.set(path.join(outCore, 'schemas.ts'), schemaModule);
  files.set(
    path.join(outCore, 'errors.ts'),
    `${GENERATED('docs/contracts/errors.json')}export const errorRegistry = ${f.errors.trimEnd()} as const;\n`,
  );
  files.set(
    path.join(outCore, 'config-keys.ts'),
    `${GENERATED('docs/contracts/domain/config-keys.json')}export const configKeyTable = ${f.keysJson.trimEnd()} as const;\n`,
  );
  return files;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const check = process.argv.includes('--check');
  const files = await build();
  const stale = [];
  for (const [file, content] of files) {
    const current = existsSync(file) ? norm(readFileSync(file, 'utf8')) : null;
    if (current === content) continue;
    if (check) stale.push(path.relative(root, file));
    else {
      mkdirSync(path.dirname(file), { recursive: true });
      writeFileSync(file, content);
    }
  }
  if (check && stale.length) {
    for (const s of stale)
      console.error(`gen-contracts: stale ${s} — run node scripts/gen-contracts.mjs`);
    process.exitCode = 1;
  } else {
    console.log(check ? 'contracts up to date' : `contracts written (${files.size} files)`);
  }
}
